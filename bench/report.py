#!/usr/bin/env python3
"""Generates bench/report.md from bench/results.jsonl (and bench/discussion.md, if present).

One result line is one attempt of one (task, arm, run); a run's attempts share one agent, and a
retry continues it (SendMessage). The numbers of a dispatch or continuation result are cumulative
for the agent (`subagent_tokens` is the agent's final context size, `tool_uses` and `duration_ms`
count from its start), so a run's cost is that of its last attempt; `processed` tokens are the sum
over all API calls in the transcript (input + cache creation + cache reads + output). A run is
solved if an attempt passed every hidden test. Invalid runs (rule violation or missing
transcript) are listed but not counted. Tokens per verified solution = all tokens an arm spent on
valid runs (solved or not) / the number of solved runs.
"""

import json
import os
import statistics
import sys

BENCH = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, BENCH)
import check  # noqa: E402

ARMS = ("qal", "rust")
TIE = 0.10
STATE = os.environ.get("BENCH_STATE", BENCH)

def runs_of(recs):
    """(task, arm, run) -> summary of its attempts, in the order they were recorded."""
    out = {}
    for r in recs:
        key = (r["task"], r["arm"], r["run"])
        if r["attempt"] == 1:
            out.pop(key, None)  # a fresh agent for the entry (after an invalid run) starts a new summary
        s = out.setdefault(key, {"attempts": 0, "passed": False, "valid": True, "failed_calls": 0, "violations": []})
        s["attempts"] = r["attempt"]
        s["tokens"] = r["dispatch"]["total_tokens"]
        s["tool_uses"] = r["dispatch"]["tool_uses"]
        s["ms"] = r["dispatch"]["duration_ms"]
        s["passed"] = r["passed"]
        s["valid"] = r["valid"]
        t = r.get("transcript") or {}
        s["failed_calls"] = t.get("failed_tool_calls", 0)
        s["processed"] = t.get("total_tokens", 0)
        s["over_budget"] = t.get("over_budget", False)
        s["violations"] = t.get("violations", [])
        s["first_pass"] = s.get("first_pass") or (r["passed"] and r["attempt"] == 1)
    return out

def fmt_k(n):
    return f"{n / 1000:.1f}k"

def cell(rs):
    if not rs:
        return "–"
    solved = sum(r["passed"] for r in rs)
    att = "/".join(str(r["attempts"]) if r["passed"] else "✗" for r in rs)
    return f"{solved}/{len(rs)} ({att}) · {fmt_k(statistics.mean(r['tokens'] for r in rs))} tok · {statistics.mean(r['tool_uses'] for r in rs):.0f} calls · {statistics.mean(r['failed_calls'] for r in rs):.0f} failed"

def winner(q, r):
    """Per task: the arm with the higher share of solved runs wins; at equal shares (above zero) the
    one with fewer mean tokens over its solved runs wins, unless within 10% (tie); if neither solved
    any run, there is no winner."""
    sq, sr = sum(x["passed"] for x in q) / len(q), sum(x["passed"] for x in r) / len(r)
    if sq != sr:
        return "QAL" if sq > sr else "Rust"
    if sq == 0:
        return "none"
    a = statistics.mean(x["tokens"] for x in q if x["passed"])
    b = statistics.mean(x["tokens"] for x in r if x["passed"])
    if abs(a - b) <= TIE * max(a, b):
        return "tie"
    return "QAL" if a < b else "Rust"

def main():
    path = os.path.join(STATE, "results.jsonl")
    recs = [json.loads(l) for l in open(path, encoding="utf-8") if l.strip()] if os.path.exists(path) else []
    runs = runs_of(recs)
    valid = {k: v for k, v in runs.items() if v["valid"]}
    sched_path = os.path.join(STATE, "schedule.json")
    sched = json.load(open(sched_path, encoding="utf-8")) if os.path.exists(sched_path) else {}
    md = ["# QAL Phase 1e — Benchmark Report\n",
          "Generated by `python3 bench/report.py` from `bench/results.jsonl`. Agents: Claude Code general-purpose subagents, model "
          f"`{sched.get('model', '?')}`, {sched.get('runs', '?')} run(s) per task and arm in the randomized order of `bench/schedule.json` "
          f"(seed `{sched.get('seed', '?')}`), at most 3 attempts per run. QAL arm: QAL through its MCP server (`qalc.py`); Rust arm: "
          "files + cargo. Both get the same task statement and the same rules (`bench/prompts/`). Verification: `bench/check.py` against "
          "the hidden tests (`bench/tasks/*/tests.json`).\n",
          "## Totals\n",
          "| | QAL | Rust |", "|---|---|---|"]
    tot = {}
    for arm in ARMS:
        rs = [v for k, v in valid.items() if k[1] == arm]
        solved = sum(r["passed"] for r in rs)
        tokens = sum(r["tokens"] for r in rs)
        tot[arm] = {
            "runs": len(rs), "solved": solved, "first": sum(bool(r.get("first_pass")) for r in rs), "tokens": tokens,
            "per_solution": tokens / solved if solved else None, "calls": sum(r["tool_uses"] for r in rs),
            "failed": sum(r["failed_calls"] for r in rs), "attempts": sum(r["attempts"] for r in rs),
            "minutes": sum(r["ms"] for r in rs) / 60000, "over": sum(bool(r.get("over_budget")) for r in rs), "processed": sum(r["processed"] for r in rs),
            "processed_per_solution": sum(r["processed"] for r in rs) / solved if solved else None,
        }
    rows = [("Valid runs", "runs", str), ("Solved (all hidden tests pass)", "solved", str), ("Solved at the first attempt", "first", str),
            ("Attempts (dispatch + retries)", "attempts", str), ("Total tokens (subagent_tokens of the dispatch results)", "tokens", fmt_k),
            ("**Tokens per verified solution**", "per_solution", lambda v: f"**{fmt_k(v)}**" if v else "–"),
            ("Processed tokens (transcripts, incl. cache reads)", "processed", fmt_k),
            ("Processed tokens per verified solution", "processed_per_solution", lambda v: fmt_k(v) if v else "–"),
            ("Tool calls (dispatch results)", "calls", str),
            ("Failed tool calls (errors seen by the agent)", "failed", str), ("Runs over the 60-tool-call budget", "over", str),
            ("Wall time (minutes)", "minutes", lambda v: f"{v:.1f}")]
    for label, key, f in rows:
        md.append(f"| {label} | {f(tot['qal'][key]) if tot['qal'][key] is not None else '–'} | {f(tot['rust'][key]) if tot['rust'][key] is not None else '–'} |")
    wins = {}
    md += ["\n## Per task\n",
           "Cell: solved runs / runs (attempt that passed per run, ✗ = not solved) · mean tokens · mean tool calls · mean failed tool calls. "
           f"Winner: higher share of solved runs, then fewer mean tokens over solved runs (tie within {int(TIE * 100)}%), see `report.py` `winner`.\n",
           "| Task | QAL | Rust | Winner |", "|---|---|---|---|"]
    for task in check.task_ids():
        q = [v for k, v in sorted(valid.items()) if k[0] == task and k[1] == "qal"]
        r = [v for k, v in sorted(valid.items()) if k[0] == task and k[1] == "rust"]
        w = winner(q, r) if q and r else "–"
        wins[w] = wins.get(w, 0) + 1
        md.append(f"| {task} | {cell(q)} | {cell(r)} | {w} |")
    md.append("\nWins: " + ", ".join(f"{k} {v}" for k, v in sorted(wins.items())) + "\n")
    invalid = {k: v for k, v in runs.items() if not v["valid"]}
    if invalid:
        md += ["## Invalid runs (not counted)\n"] + [f"- {k[0]} {k[1]} run {k[2]}: {'; '.join(v['violations'][:3]) or 'transcript not found'}" for k, v in sorted(invalid.items())] + [""]
    md += ["## Threats to validity\n",
           "- **Prior knowledge:** the model has seen a great deal of Rust and no QAL; the QAL arm learns the language from the tool descriptions in its prompt.",
           "- **Prompt size:** the QAL prompt carries the MCP tool descriptions (the language reference, about 11 KB) that an MCP client would put in context; "
           "the Rust prompt has none. This cost is counted, because it is part of using QAL.",
           "- **Transport:** the QAL arm reaches the MCP server through a shell client (`qalc.py`), not as native tools; each call also costs a Bash invocation.",
           "- **Sample size:** 20 tasks, few runs, one model: differences of a few tasks are within noise.",
           "- **Task choice:** the tasks are small CLI programs fixed before the measurement; the statements and limits were written for both arms and "
           "checked with reference solutions in both languages and an independent oracle.",
           "- **Self-reported rules:** isolation from the hidden tests relies on the prompt rules plus a transcript audit (`run.py audit`), not on a sandbox; "
           "at check time Rust programs run unsandboxed, QAL programs only with `io` (and `fs:data`).\n"]
    disc = os.path.join(BENCH, "discussion.md")
    if os.path.exists(disc):
        md += ["## Discussion\n", open(disc, encoding="utf-8").read().strip() + "\n"]
    out = os.path.join(STATE, "report.md")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(md))
    print(f"wrote {out}")

if __name__ == "__main__":
    main()
